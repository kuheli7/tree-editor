/** Builds the default policy tree, positioned by the same layout engine the Auto-Layout button uses. */
export function createMockTree(): { nodes: PolicyNode[]; edges: PolicyEdge[] } {
  const nodes: PolicyNode[] = seeds.map((seed) => ({
    id: seed.id,
    type: seed.kind,
    position: { x: 0, y: 0 },
    data: {
      label: seed.label,
      ruleId: seed.ruleId,
      description: seed.description ?? "",
      severity: seed.severity ?? "medium",
      status: seed.status ?? "active",
      parameters: seed.parameters ?? [],
      tags: seed.tags ?? [],
    },
  }));
  const edges = seeds.filter((s) => s.parent).map((s) => createEdge(s.parent!, s.id));
  return { nodes: autoLayout(nodes, edges, "TB"), edges };
}
